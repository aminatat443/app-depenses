const { AsyncLocalStorage } = require('node:async_hooks');
const { Pool, types } = require('pg');

types.setTypeParser(1082, (value) => value);
types.setTypeParser(1700, (value) => Number(value));

const transactionStorage = new AsyncLocalStorage();
const poolOptions = process.env.DATABASE_URL
  ? { connectionString: process.env.DATABASE_URL }
  : {
    host: process.env.PGHOST || '/var/run/postgresql',
    port: process.env.PGPORT ? Number(process.env.PGPORT) : undefined,
    database: process.env.PGDATABASE || 'app_depenses',
    user: process.env.PGUSER || process.env.USER,
    password: process.env.PGPASSWORD || undefined,
  };
const pool = new Pool(poolOptions);
const normalizeRevenueSource = (value) => String(value || '')
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLocaleLowerCase('fr')
  .trim();

const postgresPlaceholders = (sql) => {
  let index = 0;
  return sql.replace(/\?/g, () => `$${++index}`);
};

const query = async (sql, params = []) => {
  const client = transactionStorage.getStore() || pool;
  return client.query(postgresPlaceholders(sql), params);
};

const db = {
  query,
  prepare(sql) {
    return {
      async all(...params) {
        const result = await query(sql, params);
        return result.rows;
      },
      async get(...params) {
        const result = await query(sql, params);
        return result.rows[0];
      },
      async run(...params) {
        const returnsId = /^\s*INSERT\b/i.test(sql)
          && !/\bRETURNING\b/i.test(sql)
          && !/^\s*INSERT\s+INTO\s+(settings|user_sessions|monthly_revenues|monthly_balances|category_seed_exclusions)\b/i.test(sql);
        const statement = returnsId
          ? `${sql.trim().replace(/;$/, '')} RETURNING id`
          : sql;
        const result = await query(statement, params);
        return {
          changes: result.rowCount,
          lastInsertRowid: result.rows[0]?.id,
        };
      },
    };
  },
  async transaction(callback) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      const result = await transactionStorage.run(client, callback);
      await client.query('COMMIT');
      return result;
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  },
  async close() {
    await pool.end();
  },
};

async function initializeDatabase() {
  await query(`
    CREATE TABLE IF NOT EXISTS categories (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      type TEXT NOT NULL DEFAULT 'ordinary',
      color TEXT DEFAULT '#7c3aed',
      is_system BOOLEAN NOT NULL DEFAULT FALSE
    );

    CREATE TABLE IF NOT EXISTS expenses (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      title TEXT NOT NULL,
      category_id BIGINT NOT NULL REFERENCES categories(id),
      amount NUMERIC(18, 2) NOT NULL,
      expense_date DATE NOT NULL,
      description TEXT,
      reference TEXT,
      beneficiary TEXT,
      paid_by TEXT,
      payment_method TEXT,
      funding_source TEXT NOT NULL DEFAULT 'current',
      receipt_path TEXT,
      month_key VARCHAR(7),
      created_by BIGINT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS grocery_items (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      item_name TEXT NOT NULL,
      purchase_date DATE,
      month_key VARCHAR(7),
      quantity NUMERIC(18, 4) NOT NULL,
      unit TEXT,
      unit_price NUMERIC(18, 2) NOT NULL,
      total_amount NUMERIC(18, 2) NOT NULL,
      notes TEXT,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      quantity_known INTEGER NOT NULL DEFAULT 1,
      unit_price_known INTEGER NOT NULL DEFAULT 1
    );

    CREATE TABLE IF NOT EXISTS import_batches (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      file_name TEXT NOT NULL,
      rows_json TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'pending',
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS backup_runs (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      file_name TEXT NOT NULL,
      created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
      storage TEXT NOT NULL DEFAULT 'local',
      status TEXT NOT NULL DEFAULT 'done',
      metadata TEXT,
      source TEXT DEFAULT 'manual'
    );

    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT
    );

    CREATE TABLE IF NOT EXISTS category_seed_exclusions (
      name TEXT PRIMARY KEY
    );

    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      email TEXT NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      role TEXT NOT NULL DEFAULT 'admin' CHECK (role = 'admin'),
      is_active BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS user_sessions (
      token_hash CHAR(64) PRIMARY KEY,
      user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at TIMESTAMPTZ NOT NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
    CREATE UNIQUE INDEX IF NOT EXISTS users_single_admin_idx ON users(role);

    CREATE TABLE IF NOT EXISTS units (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      floor TEXT NOT NULL CHECK (floor IN ('Rez-de-chaussée', '1er étage', '2e étage', '3e étage')),
      label TEXT NOT NULL,
      housing_type TEXT,
      is_active BOOLEAN NOT NULL DEFAULT TRUE,
      notes TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (floor, label)
    );

    CREATE TABLE IF NOT EXISTS tenants (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      unit_id BIGINT NOT NULL REFERENCES units(id) ON DELETE RESTRICT,
      first_name TEXT NOT NULL,
      last_name TEXT NOT NULL,
      people_count INTEGER NOT NULL DEFAULT 1 CHECK (people_count > 0),
      monthly_rent NUMERIC(18, 2) NOT NULL CHECK (monthly_rent >= 0),
      entry_date DATE,
      phone TEXT,
      is_active BOOLEAN NOT NULL DEFAULT TRUE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS rent_obligations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      tenant_id BIGINT NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
      month_key VARCHAR(7) NOT NULL,
      expected_amount NUMERIC(18, 2) NOT NULL CHECK (expected_amount >= 0),
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (tenant_id, month_key)
    );

    CREATE TABLE IF NOT EXISTS rent_payments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      obligation_id BIGINT NOT NULL REFERENCES rent_obligations(id) ON DELETE RESTRICT,
      amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
      payment_date DATE NOT NULL,
      received_month_key VARCHAR(7),
      payment_method TEXT,
      comment TEXT,
      created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS income_categories (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      is_system BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS incomes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      income_date DATE NOT NULL,
      title TEXT NOT NULL,
      category_id BIGINT NOT NULL REFERENCES income_categories(id) ON DELETE RESTRICT,
      amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
      source TEXT NOT NULL,
      payment_method TEXT,
      month_key VARCHAR(7) NOT NULL,
      comment TEXT,
      created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS monthly_revenues (
      month_key VARCHAR(7) PRIMARY KEY,
      pape_amount NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (pape_amount >= 0),
      pape_received_date DATE,
      pension_amount NUMERIC(18, 2) NOT NULL DEFAULT 180000 CHECK (pension_amount >= 0),
      pension_received_date DATE,
      comment TEXT,
      created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS savings_accounts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL UNIQUE,
      is_protected BOOLEAN NOT NULL DEFAULT FALSE,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS savings_transactions (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id BIGINT NOT NULL REFERENCES savings_accounts(id) ON DELETE RESTRICT,
      transaction_date DATE NOT NULL,
      transaction_type TEXT NOT NULL CHECK (transaction_type IN ('deposit', 'withdrawal')),
      amount NUMERIC(18, 2) NOT NULL CHECK (amount > 0),
      comment TEXT,
      related_expense_id BIGINT REFERENCES expenses(id) ON DELETE SET NULL,
      created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS savings_balance_snapshots (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      account_id BIGINT NOT NULL REFERENCES savings_accounts(id) ON DELETE RESTRICT,
      month_key VARCHAR(7) NOT NULL,
      amount NUMERIC(18, 2) NOT NULL CHECK (amount >= 0),
      source_file_name TEXT,
      source_sheet TEXT,
      source_row INTEGER,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
      UNIQUE (account_id, month_key)
    );

    CREATE TABLE IF NOT EXISTS monthly_balances (
      month_key VARCHAR(7) PRIMARY KEY,
      opening_override NUMERIC(18, 2),
      correction_reason TEXT,
      updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS balance_adjustments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      month_key VARCHAR(7) NOT NULL,
      previous_opening NUMERIC(18, 2),
      new_opening NUMERIC(18, 2) NOT NULL,
      reason TEXT NOT NULL,
      changed_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS audit_log (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
      entity_type TEXT NOT NULL,
      entity_id TEXT NOT NULL,
      action TEXT NOT NULL,
      before_data JSONB,
      after_data JSONB,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    CREATE TABLE IF NOT EXISTS expense_attachments (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      expense_id BIGINT NOT NULL REFERENCES expenses(id) ON DELETE CASCADE,
      file_name TEXT NOT NULL,
      storage_path TEXT NOT NULL,
      mime_type TEXT NOT NULL,
      file_size BIGINT NOT NULL CHECK (file_size > 0),
      uploaded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
      created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );

    ALTER TABLE categories ADD COLUMN IF NOT EXISTS is_system BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS beneficiary TEXT;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS paid_by TEXT;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS payment_method TEXT;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS funding_source TEXT NOT NULL DEFAULT 'current';
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS receipt_path TEXT;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS month_key CHAR(7);
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS created_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
    ALTER TABLE expenses ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP;
    ALTER TABLE backup_runs ADD COLUMN IF NOT EXISTS source TEXT DEFAULT 'manual';
    ALTER TABLE grocery_items ADD COLUMN IF NOT EXISTS quantity_known INTEGER NOT NULL DEFAULT 1;
    ALTER TABLE grocery_items ADD COLUMN IF NOT EXISTS unit_price_known INTEGER NOT NULL DEFAULT 1;
    ALTER TABLE grocery_items ADD COLUMN IF NOT EXISTS month_key VARCHAR(7);
    ALTER TABLE grocery_items ALTER COLUMN purchase_date DROP NOT NULL;

    CREATE INDEX IF NOT EXISTS expenses_date_idx ON expenses(expense_date DESC);
    CREATE INDEX IF NOT EXISTS expenses_category_date_idx ON expenses(category_id, expense_date DESC);
    CREATE INDEX IF NOT EXISTS rent_obligations_month_idx ON rent_obligations(month_key);
    CREATE INDEX IF NOT EXISTS rent_payments_date_idx ON rent_payments(payment_date DESC);
    CREATE INDEX IF NOT EXISTS incomes_date_idx ON incomes(income_date DESC);
    CREATE INDEX IF NOT EXISTS savings_transactions_date_idx ON savings_transactions(transaction_date DESC);
    CREATE INDEX IF NOT EXISTS savings_balance_snapshots_month_idx ON savings_balance_snapshots(month_key DESC);
    CREATE INDEX IF NOT EXISTS audit_log_entity_idx ON audit_log(entity_type, entity_id, created_at DESC);
  `);
  await query(`
    ALTER TABLE expenses ALTER COLUMN month_key TYPE VARCHAR(7);
    ALTER TABLE expenses ALTER COLUMN expense_date DROP NOT NULL;
    ALTER TABLE rent_obligations ALTER COLUMN month_key TYPE VARCHAR(7);
    ALTER TABLE rent_payments ALTER COLUMN payment_date DROP NOT NULL;
    ALTER TABLE rent_payments ADD COLUMN IF NOT EXISTS received_month_key VARCHAR(7);
    CREATE INDEX IF NOT EXISTS rent_payments_received_month_idx ON rent_payments(received_month_key);
    ALTER TABLE incomes ALTER COLUMN income_date DROP NOT NULL;
    ALTER TABLE incomes ALTER COLUMN month_key TYPE VARCHAR(7);
    ALTER TABLE savings_accounts ADD COLUMN IF NOT EXISTS is_protected BOOLEAN NOT NULL DEFAULT FALSE;
    ALTER TABLE savings_transactions ADD COLUMN IF NOT EXISTS related_expense_id BIGINT REFERENCES expenses(id) ON DELETE SET NULL;
    ALTER TABLE monthly_balances ALTER COLUMN month_key TYPE VARCHAR(7);
    ALTER TABLE balance_adjustments ALTER COLUMN month_key TYPE VARCHAR(7);
    DO $$
    BEGIN
      IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'expenses_created_by_fkey') THEN
        ALTER TABLE expenses ADD CONSTRAINT expenses_created_by_fkey
          FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL;
      END IF;
    END
    $$;
    UPDATE categories SET type = 'boutique', is_system = TRUE WHERE name = 'Compte boutique';
  `);

  const defaults = [
    ['achats alimentaires complémentaires', '#c48c6a'],
    ['Dépenses alimentaires', '#55917f'],
    ['Compte boutique', '#147967'],
    ['Scolarité et frais éducatifs', '#7889a1'],
    ['Hygiène et beauté', '#a98575'],
    ['Aumônes et dons', '#c19661'],
    ['entretien de la maison', '#718b83'],
    ['Réparations', '#84958c'],
    ['Santé', '#d88370'],
    ['Transport', '#6795aa'],
    ['Alimentation des animaux', '#879a73'],
    ['Autres dépenses', '#929d99'],
    ['Dépenses exceptionnelles', '#bb7966'],
    ['Depenses imprevues', '#e7aa65'],
    ['Factures', '#6795aa'],
  ];
  await db.transaction(async () => {
    await db.prepare('DELETE FROM category_seed_exclusions WHERE name = ?').run('Autres dépenses');
    for (const [name, color] of defaults) {
      const excluded = await db.prepare('SELECT 1 FROM category_seed_exclusions WHERE name = ?').get(name);
      if (excluded) continue;
      await db.prepare(`
        INSERT INTO categories (name, type, color, is_system)
        VALUES (?, 'ordinary', ?, TRUE)
        ON CONFLICT (name) DO NOTHING
      `).run(name, color);
    }

    const categorySyncKey = 'render_categories_sync_v1';
    const categorySync = await db.prepare('SELECT value FROM settings WHERE key = ?').get(categorySyncKey);
    if (!categorySync) {
      const mergedCategories = [
        ['Pain et achats alimentaires complémentaires', 'achats alimentaires complémentaires'],
        ['Facture d’eau', 'Factures'],
        ['Facture d’électricité', 'Factures'],
        ['Facture Wi-Fi', 'Factures'],
        ['Eau', 'Factures'],
        ['Électricité', 'Factures'],
        ['Internet / Wi-Fi', 'Factures'],
        ['Entretien', 'entretien de la maison'],
        ['Réparations et entretien de la maison', 'entretien de la maison'],
        ['Santé, consultations et médicaments', 'Santé'],
        ['Santé / Ordonnances', 'Santé'],
        ['Scolarité', 'Scolarité et frais éducatifs'],
        ['Autres', 'Autres dépenses'],
        ['Argent de poche des enfants', 'Autres dépenses'],
        ['Renforcement et aides financières', 'Autres dépenses'],
        ['Salaire femme de ménage', 'Autres dépenses'],
        ['Dépenses exceptionnelles ou imprévues', 'Dépenses exceptionnelles'],
      ];
      const fallback = await db.prepare("SELECT id FROM categories WHERE name = 'Autres dépenses'").get();
      for (const [sourceName, targetName] of mergedCategories) {
        const source = await db.prepare('SELECT id FROM categories WHERE name = ?').get(sourceName);
        if (!source) continue;
        const target = await db.prepare('SELECT id FROM categories WHERE name = ?').get(targetName) || fallback;
        if (!target || Number(source.id) === Number(target.id)) continue;
        await db.prepare('UPDATE expenses SET category_id = ?, updated_at = CURRENT_TIMESTAMP WHERE category_id = ?')
          .run(target.id, source.id);
        await db.prepare('DELETE FROM categories WHERE id = ?').run(source.id);
      }
      const defaultNames = defaults.map(([name]) => name);
      await db.prepare(`
        UPDATE categories SET is_system = TRUE
        WHERE name IN (${defaultNames.map(() => '?').join(', ')})
      `).run(...defaultNames);
      await db.prepare('INSERT INTO settings (key, value) VALUES (?, ?)')
        .run(categorySyncKey, 'completed');
    }

    const incomeDefaults = ['Pension père', 'Pape', 'Autres recettes'];
    for (const name of incomeDefaults) {
      await db.prepare(`
        INSERT INTO income_categories (name, is_system) VALUES (?, TRUE)
        ON CONFLICT (name) DO NOTHING
      `).run(name);
    }
  });

  await db.transaction(async () => {
    const accounts = await db.prepare('SELECT id, name, is_protected FROM savings_accounts').all();
    const protectedAccounts = accounts.filter((account) => (
      normalizeRevenueSource(account.name) === 'epargne pension pere'
    ));
    if (!protectedAccounts.length) {
      const account = await db.prepare(`
        INSERT INTO savings_accounts (name, is_protected)
        VALUES ('Épargne pension père', TRUE)
        RETURNING id, name
      `).get();
      await db.prepare(`
        INSERT INTO audit_log (entity_type, entity_id, action, after_data)
        VALUES ('savings_account', ?, 'protected_account_created', ?::jsonb)
      `).run(String(account.id), JSON.stringify({ name: account.name, is_protected: true }));
    } else {
      for (const account of protectedAccounts) {
        if (account.is_protected) continue;
        await db.prepare(`
          UPDATE savings_accounts SET is_protected = TRUE, updated_at = CURRENT_TIMESTAMP
          WHERE id = ?
        `).run(account.id);
        await db.prepare(`
          INSERT INTO audit_log (entity_type, entity_id, action, before_data, after_data)
          VALUES ('savings_account', ?, 'protected_account_enabled', ?::jsonb, ?::jsonb)
        `).run(
          String(account.id),
          JSON.stringify({ name: account.name, is_protected: false }),
          JSON.stringify({ name: account.name, is_protected: true }),
        );
      }
    }

    const backfillKey = 'monthly_revenues_backfill_v1';
    const backfill = await db.prepare('SELECT value FROM settings WHERE key = ?').get(backfillKey);
    if (backfill) return;

    const legacyRows = await db.prepare(`
      SELECT month_key, source, amount, income_date, comment
      FROM incomes
      WHERE month_key ~ '^\\d{4}-(0[1-9]|1[0-2])$'
      ORDER BY month_key, id
    `).all();
    const byMonth = new Map();
    for (const row of legacyRows) {
      const source = normalizeRevenueSource(row.source);
      const sourceKey = source === 'pape' ? 'pape' : source === 'pension pere' ? 'pension' : null;
      if (!sourceKey) continue;
      const month = byMonth.get(row.month_key) || {
        pape: { amount: 0, date: null },
        pension: { amount: 0, date: null },
        comments: new Set(),
      };
      month[sourceKey].amount += Number(row.amount);
      if (row.income_date && (!month[sourceKey].date || row.income_date < month[sourceKey].date)) {
        month[sourceKey].date = row.income_date;
      }
      if (row.comment) month.comments.add(row.comment);
      byMonth.set(row.month_key, month);
    }

    for (const [monthKey, month] of byMonth) {
      await db.prepare(`
        INSERT INTO monthly_revenues (
          month_key, pape_amount, pape_received_date, pension_amount, pension_received_date, comment
        ) VALUES (?, ?, ?, ?, ?, ?)
        ON CONFLICT (month_key) DO NOTHING
      `).run(
        monthKey,
        month.pape.amount,
        month.pape.date,
        month.pension.amount,
        month.pension.date,
        [...month.comments].join(' · ') || 'Montants repris des recettes historiques.',
      );
    }
    await db.prepare('INSERT INTO settings (key, value) VALUES (?, ?)')
      .run(backfillKey, `done:${byMonth.size}`);
  });

  await db.transaction(async () => {
    const migrationKey = 'rent_sheet_previous_month_v1';
    const migration = await db.prepare('SELECT value FROM settings WHERE key = ?').get(migrationKey);
    if (migration) return;

    await db.prepare(`
      UPDATE rent_payments p
      SET received_month_key = COALESCE(to_char(p.payment_date, 'YYYY-MM'), o.month_key)
      FROM rent_obligations o
      WHERE o.id = p.obligation_id AND p.received_month_key IS NULL
    `).run();

    const importedObligations = await db.prepare(`
      SELECT DISTINCT o.id, o.tenant_id, o.month_key
      FROM rent_obligations o
      JOIN rent_payments p ON p.obligation_id = o.id
      WHERE p.comment LIKE 'Statut source : %'
        AND o.month_key ~ '^\\d{4}-(0[1-9]|1[0-2])$'
      ORDER BY o.month_key, o.id
    `).all();

    for (const obligation of importedObligations) {
      const [year, month] = obligation.month_key.split('-').map(Number);
      const previousMonth = new Date(Date.UTC(year, month - 2, 1));
      const previousMonthKey = `${previousMonth.getUTCFullYear()}-${String(previousMonth.getUTCMonth() + 1).padStart(2, '0')}`;
      const conflict = await db.prepare(`
        SELECT id FROM rent_obligations
        WHERE tenant_id = ? AND month_key = ? AND id <> ?
      `).get(obligation.tenant_id, previousMonthKey, obligation.id);
      if (conflict) {
        throw new Error(`Impossible de rattacher le loyer au mois précédent : une obligation existe déjà pour ${previousMonthKey}.`);
      }

      await db.prepare('UPDATE rent_obligations SET month_key = ? WHERE id = ?')
        .run(previousMonthKey, obligation.id);
      await db.prepare(`
        INSERT INTO audit_log (entity_type, entity_id, action, before_data, after_data)
        VALUES ('rent_obligation', ?, 'period_corrected', ?::jsonb, ?::jsonb)
      `).run(
        String(obligation.id),
        JSON.stringify({ month_key: obligation.month_key }),
        JSON.stringify({ month_key: previousMonthKey, cash_month_preserved: true }),
      );
    }

    await db.prepare('INSERT INTO settings (key, value) VALUES (?, ?)')
      .run(migrationKey, `done:${importedObligations.length}`);
  });
}

module.exports = { db, initializeDatabase, query };
